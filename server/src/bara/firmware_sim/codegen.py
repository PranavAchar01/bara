"""Write the firmware project for one build: bara_config.h and bara_inputs.h from the I/O plan,
the linker script for the board, and the portable C sources next to them."""

from __future__ import annotations

import re
import shutil
from dataclasses import asdict, dataclass, field
from pathlib import Path
from typing import Any

from .mcu import BOARDS, Board, pin_number

C_DIR = Path(__file__).parent / "c"
FW_VERSION = "1.0"

KIND_CODE = {"button": 0, "key": 1, "switch": 2, "encoder": 3, "axis": 4, "mkey": 5}


@dataclass
class FwConfig:
    """What the agent (or the person) can change, then rebuild."""

    blink_ms: int = 500
    debounce_ms: int = 5
    tone_ms: int = 40
    axis_deadzone: int = 6
    led_on_press: bool = True
    labels: dict[str, str] = field(default_factory=dict)  # input id -> label
    codes: dict[str, str] = field(default_factory=dict)  # input id -> keycode

    def to_dict(self) -> dict[str, Any]:
        return asdict(self)

    @classmethod
    def from_dict(cls, d: dict[str, Any] | None) -> FwConfig:
        d = d or {}
        cfg = cls()
        for k in ("blink_ms", "debounce_ms", "tone_ms", "axis_deadzone"):
            if k in d:
                setattr(cfg, k, max(1, min(int(d[k]), 60_000)))
        if "led_on_press" in d:
            cfg.led_on_press = bool(d["led_on_press"])
        cfg.labels = {str(k): str(v) for k, v in (d.get("labels") or {}).items()}
        cfg.codes = {str(k): str(v) for k, v in (d.get("codes") or {}).items()}
        return cfg


def c_str(s: str, limit: int = 24) -> str:
    """A safe C string literal: printable ASCII only, no quotes or backslashes."""
    s = re.sub(r"[^ -~]", "", s).replace("\\", "/").replace('"', "'")
    return '"' + s[:limit] + '"'


def _pin(board: Board, pin: str | None) -> int:
    return pin_number(board, pin) if pin else 255


def config_header(io: dict[str, Any], cfg: FwConfig, board: Board) -> str:
    outputs = {o["id"]: o for o in io["outputs"]}
    screen = next((o for o in io["outputs"] if o["kind"] == "display"), None)
    led = outputs.get("led:onboard") or next((o for o in io["outputs"] if o["kind"] == "led"), None)
    tone = next((o for o in io["outputs"] if o["kind"] == "tone"), None)
    serial = outputs.get("serial") or {}
    matrix = io.get("matrix") or None
    rows = screen["rows"] if screen else 4
    cols = screen["cols"] if screen else 21
    name = (io.get("device") or {}).get("name") or io.get("kind") or "device"
    lines = [
        "/* generated by bara: do not edit, change the build and rebuild */",
        "#ifndef BARA_CONFIG_H",
        "#define BARA_CONFIG_H",
        f"#define BARA_NAME {c_str(str(name), 32)}",
        f"#define BARA_MCU {c_str(board.label, 32)}",
        f'#define BARA_FW_VERSION "{FW_VERSION}"',
        f"#define BLINK_MS {cfg.blink_ms}",
        f"#define DEBOUNCE_MS {cfg.debounce_ms}",
        f"#define TONE_MS {cfg.tone_ms}",
        f"#define AXIS_DEADZONE {cfg.axis_deadzone}",
        f"#define SCREEN_ROWS {max(1, min(rows, 8))}",
        f"#define SCREEN_COLS {max(8, min(cols, 32))}",
        f"#define LED_PIN {_pin(board, led.get('pin')) if led else 255}",
        f"#define LED_ACTIVE_LOW {1 if led and led.get('active_low') else 0}",
        f"#define LED_ON_PRESS {1 if cfg.led_on_press else 0}",
        f"#define TONE_PIN {_pin(board, tone.get('pin')) if tone else 255}",
        f"#define SERIAL_TX_PIN {_pin(board, serial.get('pin'))}",
        f"#define DEVICE_KEYBOARD {1 if io.get('kind') == 'keyboard' else 0}",
        f"#define N_INPUTS {max(1, len(io['inputs']))}",
        f"#define N_AXES {sum(1 for i in io['inputs'] if i['kind'] == 'axis')}",
        f"#define IMAGE_ORIGIN 0x{board.image_origin:X}u",
    ]
    if matrix:
        pins = ", ".join(str(_pin(board, p)) for p in matrix["row_pins"])
        lines += [f"#define MATRIX_ROWS {matrix['rows']}", f"#define MATRIX_ROW_PINS {{{pins}}}"]
    else:
        lines += ["#define MATRIX_ROWS 0", "#define MATRIX_ROW_PINS {0}"]
    lines += ["#endif", ""]
    return "\n".join(lines)


def input_rows(io: dict[str, Any], cfg: FwConfig) -> list[dict[str, Any]]:
    """The firmware's input table, in order, with the final label and kind of each."""
    out = []
    for i in io["inputs"]:
        kind = i["kind"]
        if kind == "key" and i.get("row_pin"):
            kind = "mkey"
        out.append({**i, "fw_kind": kind, "label": cfg.labels.get(i["id"]) or i["label"]})
    return out


def inputs_header(io: dict[str, Any], cfg: FwConfig, board: Board) -> str:
    rows = input_rows(io, cfg)
    body = []
    for r in rows:
        pin2 = r.get("row_pin") if r["fw_kind"] == "mkey" else r.get("pin_b")
        label, note = c_str(r["label"]), re.sub(r"[^ -~]|\*/", "", r["id"])
        kind, p1, p2 = KIND_CODE[r["fw_kind"]], _pin(board, r.get("pin")), _pin(board, pin2)
        hid, adc = int(r.get("hid") or 0), int(r.get("adc") or 0)
        body.append(f"  {{{label}, {kind}, {p1}, {p2}, 0x{hid:02X}, {adc}}}, /* {note} */")
    if not body:
        body = ['  {"none", 0, 255, 255, 0, 0},']
    return (
        "/* generated by bara */\n"
        "static const bara_input_t BARA_INPUTS[N_INPUTS] = {\n" + "\n".join(body) + "\n};\n"
    )


def linker_script(board: Board) -> str:
    if board.family == "rp2040":
        # Loaded straight into SRAM (the no_flash layout): code first, data and stack above it.
        code = (board.ram_origin, 0x30000)
        ram = (board.ram_origin + 0x30000, board.ram_size - 0x30000)
    else:
        code = (board.image_origin, board.flash_size - board.image_origin - 0x8000)
        ram = (board.ram_origin, board.ram_size)
    return f"""/* generated by bara for {board.label} */
ENTRY(Reset_Handler)
MEMORY {{
  CODE (rx) : ORIGIN = 0x{code[0]:08X}, LENGTH = 0x{code[1]:X}
  RAM (rwx) : ORIGIN = 0x{ram[0]:08X}, LENGTH = 0x{ram[1]:X}
}}
SECTIONS {{
  .text : {{ KEEP(*(.vectors)) *(.text*) *(.rodata*) . = ALIGN(4); }} > CODE
  .data : {{ __data_start = .; *(.data*) . = ALIGN(4); __data_end = .; }} > RAM AT > CODE
  __data_load = LOADADDR(.data);
  .bss (NOLOAD) : {{ __bss_start = .; *(.bss*) *(COMMON) . = ALIGN(4); __bss_end = .; }} > RAM
  __stack_top = ORIGIN(RAM) + LENGTH(RAM);
  /DISCARD/ : {{ *(.ARM.exidx*) *(.comment) }}
}}
"""


def write_project(io: dict[str, Any], cfg: FwConfig, out: Path) -> dict[str, Any]:
    """Write every source file of the firmware into out/src. Returns the file list."""
    board = BOARDS.get(io["mcu"]["board_id"]) or BOARDS["nice_nano_v2"]
    src = out / "src"
    src.mkdir(parents=True, exist_ok=True)
    for f in C_DIR.iterdir():
        if f.suffix in (".c", ".h"):
            shutil.copyfile(f, src / f.name)
    (src / "bara_config.h").write_text(config_header(io, cfg, board))
    (src / "bara_inputs.h").write_text(inputs_header(io, cfg, board))
    (src / "link.ld").write_text(linker_script(board))
    return {
        "board": board,
        "files": sorted(p.name for p in src.iterdir()),
        "src": src,
    }
