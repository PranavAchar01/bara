"""Curated part list: which KiCad footprint, symbol and 3D model each catalog part uses.

This file only chooses upstream files and names the part. Every number in a part
record (pads, courtyard, bbox, height, pin names) is extracted from those files by
build.py. The few hand-entered electrical values are marked with their own
provenance (extractor "human", verified "none") in the built record.

Footprint refs: "kicad:<Lib>:<Name>" for the installed KiCad library, or
"<source>:<path relative to that source's root>" for a third-party library.
Symbol refs: "kicad:<Lib>:<Name>" or "<source>:<path>#<Name>".
"""

from __future__ import annotations

from dataclasses import dataclass, field
from typing import Any


@dataclass(frozen=True)
class ModelSpec:
    """A model used instead of (or besides) the footprint's own model entries.

    align "seat": rotate, then translate so the model's XY bbox centre sits on the
    footprint courtyard centre (or the origin) and its lowest point on z = 0. The
    translation is computed from the model geometry, never typed in.
    """

    source: str
    path: str
    rotate: tuple[float, float, float] = (0.0, 0.0, 0.0)
    align: str | None = "seat"
    z_base: float = 0.0


@dataclass(frozen=True)
class Entry:
    part_id: str
    name: str
    kind: str
    function: str
    footprint: str | None = None
    symbol: str | None = None
    more_functions: tuple[str, ...] = ()
    models: tuple[ModelSpec, ...] = ()
    model_filter: tuple[str, ...] = ()  # keep only footprint models whose path has one of these
    mesh_from: str | None = None  # reuse another part's GLB (same form factor), flagged
    mesh_note: str | None = None
    whole_board: str | None = None  # "<source>:<path>.kicad_pcb": export the full board
    board_half: str | None = None  # "left" | "right": keep one half of a two-up board file
    summary: str | None = None
    manufacturer: str | None = None
    mpn: str | None = None
    facets: dict[str, Any] = field(default_factory=dict)
    electrical: dict[str, float] = field(default_factory=dict)
    interfaces: tuple[dict[str, Any], ...] = ()  # hand-entered, provenance human
    standards: tuple[str, ...] = ()
    color: str | None = None
    datasheet: str | None = None
    bbox_note: str | None = None  # for meshless parts: dims from a named designation


def E(
    part_id: str, name: str, kind: str, function: str, footprint: str | None = None, **kw: Any
) -> Entry:
    if "models" in kw:
        kw["models"] = tuple(kw["models"])
    if "more_functions" in kw:
        kw["more_functions"] = tuple(kw["more_functions"])
    if "model_filter" in kw:
        kw["model_filter"] = tuple(kw["model_filter"])
    if "interfaces" in kw:
        kw["interfaces"] = tuple(kw["interfaces"])
    if "standards" in kw:
        kw["standards"] = tuple(kw["standards"])
    return Entry(part_id, name, kind, function, footprint, **kw)


def _pwr_in(iid: str, vmin: float, vmax: float, label: str) -> dict[str, Any]:
    return {
        "id": iid,
        "type": "power_in",
        "label": label,
        "params": {"v_min_v": vmin, "v_max_v": vmax},
    }


def _pwr_out(iid: str, vnom: float, imax: float, label: str) -> dict[str, Any]:
    return {
        "id": iid,
        "type": "power_out",
        "label": label,
        "params": {"v_nom_v": vnom, "i_max_a": imax},
    }


